async function geocode(place) {
  const url = `https://maps.googleapis.com/maps/api/geocode/json?address=${encodeURIComponent(
    place
  )}&key=${process.env.GOOGLE_API_KEY}`;

  const res = await fetch(url);
  const data = await res.json();

  if (!data.results || !data.results.length) {
    console.error("NO RESULT:", place);
    return null;
  }
  const loc = data.results[0].geometry.location;
  return `${loc.lat},${loc.lng}`;
}

(async () => {
  const out = {};
  for (const resort of resorts) {
    console.log("Geocoding:", resort);
    const coords = await geocode(resort);

    if (coords) {
      out[resort] = coords;
      console.log(" =>", coords);
    } else {
      out[resort] = "ERROR_NOT_FOUND";
    }

    // 1.5 second delay to avoid rate limits
    await new Promise((r) => setTimeout(r, 1500));
  }

  const file = `export const coordinatesList = ${JSON.stringify(
    out,
    null,
    2
  )};\n`;

  fs.writeFileSync("coordinatesList.js", file);
  console.log("Done! See coordinatesList.js");
})();
